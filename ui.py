    def refresh_deep_lists(self):
        self.deep_series_list.delete(0, "end")
        for series in self.deep_config.get("series", []):
            self.deep_series_list.insert("end", series.get("title", "未命名系列"))
        if self.deep_config.get("series"):
            self.deep_series_list.selection_set(0)
            self.on_deep_series_select()

    def get_selected_deep_series_index(self):
        selection = self.deep_series_list.curselection()
        return selection[0] if selection else -1

    def get_selected_deep_episode_index(self):
        selection = self.deep_episode_list.curselection()
        return selection[0] if selection else -1

    def on_deep_series_select(self, _event=None):
        index = self.get_selected_deep_series_index()
        if index < 0:
            return
        series = self.deep_config.get("series", [])[index]
        self.deep_series_title_var.set(series.get("title", ""))
        self.deep_series_desc_var.set(series.get("description", ""))

        self.deep_episode_list.delete(0, "end")
        for episode in series.get("episodes", []):
            if episode.get("generated") and episode.get("video_path"):
                status = "已生成"
            elif episode.get("review_ready") and episode.get("script_path"):
                status = "待生成视频"
            else:
                status = "未生成"
            self.deep_episode_list.insert("end", f"[{status}] {episode.get('title', '未命名主题')}")
        if series.get("episodes"):
            self.deep_episode_list.selection_set(0)
            self.on_deep_episode_select()
        else:
            self.deep_episode_title_var.set("")
            self.deep_episode_question_var.set("")

    def on_deep_episode_select(self, _event=None):
        series_index = self.get_selected_deep_series_index()
        episode_index = self.get_selected_deep_episode_index()
        if series_index < 0 or episode_index < 0:
            return
