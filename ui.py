def configure_tk_runtime():
    base_prefix = getattr(sys, "base_prefix", "")
    tcl_dir = os.path.join(base_prefix, "tcl", "tcl8.6")
    tk_dir = os.path.join(base_prefix, "tcl", "tk8.6")
