    def refresh_deep_lists(self):
        if not hasattr(self, "deep_series_table"):
            return
        self.deep_series_row_map = {}
        self.deep_episode_row_map = {}
        self.deep_series_table.delete(*self.deep_series_table.get_children())
        self.deep_episode_table.delete(*self.deep_episode_table.get_children())

        for series_index, series in enumerate(self.deep_config.get("series", [])):
            row_id = f"s{series_index}"
            self.deep_series_row_map[row_id] = series_index
            self.deep_series_table.insert(
                "",
                "end",
                iid=row_id,
                values=(
                    series.get("title", "未命名系列"),
                    len(series.get("episodes", [])),
                    series.get("description", ""),
                ),
            )
        children = self.deep_series_table.get_children()
        if children:
            self.deep_series_table.selection_set(children[0])
            self.deep_series_table.focus(children[0])
            self.on_deep_series_select()

    def refresh_deep_episode_table(self, series_index):
        self.deep_episode_row_map = {}
        self.deep_episode_table.delete(*self.deep_episode_table.get_children())
        if series_index < 0:
            return
        series_list = self.deep_config.get("series", [])
        if series_index >= len(series_list):
            return
        for episode_index, episode in enumerate(series_list[series_index].get("episodes", [])):
            row_id = f"e{series_index}_{episode_index}"
            self.deep_episode_row_map[row_id] = (series_index, episode_index)
            self.deep_episode_table.insert(
                "",
                "end",
                iid=row_id,
                values=(
                    episode.get("title", "未命名主题"),
                    self.get_episode_status(episode),
                    episode.get("question", ""),
                    episode.get("generated_at", ""),
                ),
            )
        children = self.deep_episode_table.get_children()
        if children:
            self.deep_episode_table.selection_set(children[0])
            self.deep_episode_table.focus(children[0])
            self.on_deep_episode_select()
        else:
            self.deep_episode_title_var.set("")
            self.deep_episode_question_var.set("")

    def get_selected_deep_series_index(self):
        if hasattr(self, "deep_series_table"):
            episode_selection = self.deep_episode_table.selection()
            if episode_selection:
                return self.deep_episode_row_map.get(episode_selection[0], (-1, -1))[0]
            series_selection = self.deep_series_table.selection()
            if series_selection:
                return self.deep_series_row_map.get(series_selection[0], -1)
            return -1
        selection = self.deep_series_list.curselection()
