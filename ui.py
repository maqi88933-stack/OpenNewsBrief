    def run_worker_subprocess(self, args):
        command = [self.worker_python, "-X", "utf8", self.worker_script] + list(args)
        env = os.environ.copy()
        env["PYTHONIOENCODING"] = "utf-8"
        env["PYTHONUTF8"] = "1"
        process = subprocess.Popen(
            command,
            cwd=main.ROOT_DIR,
            env=env,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            encoding="utf-8",
            errors="replace",
            bufsize=1,
        )

        result = None
        if process.stdout is not None:
            for line in process.stdout:
                if line.startswith("__RESULT__"):
                    result = json.loads(line[len("__RESULT__"):].strip())
                    continue
                self.append_log(line)

        return_code = process.wait()
        if return_code != 0:
            self.append_log(f"子进程执行失败，退出码：{return_code}\n")
        return result

